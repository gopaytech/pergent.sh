func TestScanTreeIgnoresLinks(t *testing.T) {
	outside := tree(t, map[string]string{
		"agents.txt": "outside instructions",
		"big.txt":    strings.Repeat("a", 600<<10),
		"d/x.go":     "package x\n",
	})
	root := tree(t, map[string]string{
		"main.go":     "package main\n",
		".git/config": "[core]\n",
		".git/x.go":   "package x\n",
	})
	for link, target := range map[string]string{
		"passwd":    "/etc/passwd",
		"etc":       "/etc",
		"AGENTS.md": filepath.Join(outside, "agents.txt"),
		"big.go":    filepath.Join(outside, "big.txt"),
		"linked":    filepath.Join(outside, "d"),
		"README.md": "main.go",
	} {
		if err := os.Symlink(target, filepath.Join(root, link)); err != nil {
			t.Fatal(err)
		}
	}
	got := scan(t, root, JobInput{Version: 1})
	if got.Files != 1 || got.SourceFiles != 1 || got.NoiseTotal != 0 || got.InstructionsBytes != 0 {
		t.Errorf("files %d, source %d, noise %d, instructions %d; want 1, 1, 0, 0",
			got.Files, got.SourceFiles, got.NoiseTotal, got.InstructionsBytes)
	}
	if got.Context != (Context{}) {
		t.Errorf("context = %+v", got.Context)
	}
}

func TestInstructionsBytes(t *testing.T) {
	root := tree(t, map[string]string{
		"AGENTS.md":                "agents text",
		".pergent/instructions.md": "team text",
	})
	// 36 + 11 + 1 for AGENTS.md, 56 + 9 + 1 for the team file.
	if got := scan(t, root, JobInput{Version: 1}); got.InstructionsBytes != 114 {
		t.Errorf("instructions bytes = %d, want 114", got.InstructionsBytes)
	}

	// An AGENTS.md over what a review can read is present, not a failed scan,
	// and its size still counts: at the cap 36 + 921600 + 1, one byte more 921638.
	for size, want := range map[int64]int{inputs.ConfigMapLimit: 921637, inputs.ConfigMapLimit + 1: 921638} {
		root := t.TempDir()
		f, err := os.Create(filepath.Join(root, "AGENTS.md"))
		if err != nil {
			t.Fatal(err)
		}
		if err := f.Truncate(size); err != nil { // sparse: zeros, so not empty
			t.Fatal(err)
		}
		f.Close()
		got := scan(t, root, JobInput{Version: 1})
		if got.InstructionsBytes != want || got.Context.AgentFile != "AGENTS.md" || got.Context.AgentFileEmpty {
			t.Errorf("AGENTS.md of %d bytes: instructions %d, context %+v; want %d", size, got.InstructionsBytes, got.Context, want)
		}
	}
}

