func TestNoiseCapped(t *testing.T) {
	files := map[string]string{}
	for i := 1; i <= 59; i++ {
		files[fmt.Sprintf("dist/f%02d.js", i)] = strings.Repeat("a", i)
	}
	long := "dist/" + strings.Repeat("a", 200) + "/" + strings.Repeat("b", 200) + "/" + strings.Repeat("c", 200) + ".js"
	files[long] = strings.Repeat("a", 1000)
	got := scan(t, tree(t, files), JobInput{Version: 1})

	if got.NoiseTotal != 60 || len(got.Noise) != MaxNoisePaths {
		t.Fatalf("total %d, listed %d", got.NoiseTotal, len(got.Noise))
	}
	for i, n := range got.Noise {
		if want := fmt.Sprintf("dist/f%02d.js", 59-i); n.Path != want || n.Size != int64(59-i) {
			t.Errorf("noise[%d] = %s %d, want %s", i, n.Path, n.Size, want)
		}
	}
}

func TestLanguagesUncovered(t *testing.T) {
	files := map[string]string{"README.md": "x", "go.sum": "x"}
	for i := 0; i < 8; i++ {
		files[fmt.Sprintf("pkg/f%d.go", i)] = "package pkg\n"
	}
	files["a.py"], files["b.PY"] = "x", "x"
	files["vendor/v.py"] = "x" // not a source file
	got := scan(t, tree(t, files), JobInput{Version: 1, Library: []ScopedSkill{
		{Name: "go", Paths: []string{"*.go"}, Assigned: true},
		{Name: "py", Paths: []string{"*.py"}}, // not assigned
	}})
	want := []Language{{Name: "Go", Files: 8}, {Name: "Python", Files: 2, Uncovered: true}}
	if got.SourceFiles != 10 || fmt.Sprint(got.Languages) != fmt.Sprint(want) {
		t.Errorf("source files %d, languages %+v", got.SourceFiles, got.Languages)
	}

	// 1 in 20 (5%) and 1 in 10 (exactly 10%) are not listed.
	for _, n := range []int{19, 9} {
		files = map[string]string{"x.rb": "x"}
		for i := 0; i < n; i++ {
			files[fmt.Sprintf("f%d.go", i)] = "package x\n"
		}
		got = scan(t, tree(t, files), JobInput{Version: 1})
		want = []Language{{Name: "Go", Files: n, Uncovered: true}}
		if fmt.Sprint(got.Languages) != fmt.Sprint(want) {
			t.Errorf("%d go: languages %+v", n, got.Languages)
		}
	}
}

