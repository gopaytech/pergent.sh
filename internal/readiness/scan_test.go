// tree writes files (path → content) below a new temporary directory.
func tree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for p, content := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func scan(t *testing.T, root string, in JobInput) JobResult {
	t.Helper()
	got, err := ScanTree(context.Background(), root, in)
	if err != nil {
		t.Fatal(err)
	}
	return got
}

func fit(t *testing.T, r JobResult, folder, name string) SkillFit {
	t.Helper()
	for _, f := range r.Skills {
		if f.Folder == folder && f.Name == name {
			return f
		}
	}
	t.Fatalf("no fit %s/%s in %+v", folder, name, r.Skills)
	return SkillFit{}
}

