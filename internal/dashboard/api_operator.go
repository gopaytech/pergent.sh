// --- views ---

// secretFields are the secrets an instance takes, in the order they are shown.
// An instance's approver (an approverKind*) decides its approve secret: an
// approve App's key, a bot user's token, or none when the review App or the
// review bot approves.
func secretFields(platform, approver string) []string {
	if platform == config.PlatformGitLab {
		if approver == approverKindReviewBot {
			return []string{instances.FieldReviewToken, instances.FieldWebhookSecret}
		}
		return []string{instances.FieldReviewToken, instances.FieldApproveToken, instances.FieldWebhookSecret}
	}
	fields := []string{instances.FieldReviewAppKey}
	switch approver {
	case approverKindApp:
		fields = append(fields, instances.FieldApproveAppKey)
	case approverKindToken:
		fields = append(fields, instances.FieldApproveToken)
	}
	return append(fields, instances.FieldWebhookSecret)
}

// configEnvs maps each secret field of a config instance to the env var
// holding it.
func configEnvs(inst instances.Instance) map[string]string {
	switch {
	case inst.GitLab != nil:
		g := inst.GitLab
		return map[string]string{
			instances.FieldReviewToken: g.ReviewTokenEnv, instances.FieldApproveToken: g.ApproveTokenEnv,
			instances.FieldWebhookSecret: g.WebhookSecretEnv,
		}
	case inst.GitHub != nil:
		g := inst.GitHub
		out := map[string]string{
			instances.FieldReviewAppKey: g.ReviewApp.PrivateKeyEnv, instances.FieldApproveToken: g.ApproveTokenEnv,
			instances.FieldWebhookSecret: g.WebhookSecretEnv,
		}
		if g.ApproveApp != nil {
			out[instances.FieldApproveAppKey] = g.ApproveApp.PrivateKeyEnv
		}
		return out
	}
	return nil
}

// lookupEnv reports whether the env var name holds a value.
func lookupEnv(name string) bool { return name != "" && os.Getenv(name) != "" }

// approverOf is the approverKind* of inst: the one it approves with.
func approverOf(inst instances.Instance) string {
	if inst.GitHub == nil {
		if inst.GitLab != nil && inst.GitLab.ApproveWithReviewBot {
			return approverKindReviewBot
		}
		return approverKindToken
	}
	switch inst.GitHub.Approver() {
	case config.ApproverReviewApp:
		return approverKindReviewApp
	case config.ApproverApp:
		return approverKindApp
	}
	return approverKindToken
}

// approverOfRow is approverOf for the instance row describes.
func approverOfRow(row store.InstanceRow) string {
	return approverOf(instances.FromRow(row))
}

// instanceView describes inst. A config instance's secrets are set when the
// env var holds a value; a dashboard instance's when the sealed value opens.
func (d *Dashboard) instanceView(ctx context.Context, inst instances.Instance) (InstanceAdminView, error) {
	v := InstanceAdminView{Name: inst.Name, Platform: inst.Platform, Source: string(inst.Source), Removing: inst.Removing,
		TrustedAuthorsOnly: inst.TrustedAuthorsOnly, MonthlyTokenQuota: inst.MonthlyTokenQuota,
		WebhookURL: config.WebhookURL(d.cfg.PublicURL, inst.Platform, inst.Name),
		Approver:   approverOf(inst), Secrets: map[string]SecretView{}}
	switch {
	case inst.GitLab != nil:
		v.URL = inst.GitLab.URL
	case inst.GitHub != nil:
		v.APIURL, v.ReviewAppID = inst.GitHub.APIURL, inst.GitHub.ReviewApp.AppID
		v.ApproveAppID = approveAppIDOf(inst)
	}
	used, err := d.Store.TokensSince(ctx, inst.Name, 0, quota.MonthStart(d.now()))
	if err != nil {
		return InstanceAdminView{}, err
	}
	v.TokensThisMonth = used
	fields := secretFields(inst.Platform, v.Approver)
	if inst.Source == instances.SourceConfig {
		envs := configEnvs(inst)
		for _, f := range fields {
			v.Secrets[f] = SecretView{Set: lookupEnv(envs[f])}
		}
		return v, nil
	}
	sealed, err := d.Store.InstanceSecrets(ctx, inst.Name)
	if err != nil {
		return InstanceAdminView{}, err
	}
	for _, f := range fields {
		sv := SecretView{}
		if s, ok := sealed[f]; ok {
			if plain, err := d.Auth.box.Open(s.Value); err == nil && len(plain) > 0 {
				at := s.UpdatedAt
				sv = SecretView{Set: true, UpdatedAt: &at}
			}
		}
		v.Secrets[f] = sv
	}
	return v, nil
}

func (d *Dashboard) listInstances(w http.ResponseWriter, r *http.Request) {
	all := d.registry.All()
	out := make([]InstanceAdminView, 0, len(all))
	for _, inst := range all {
		v, err := d.instanceView(r.Context(), inst)
		if err != nil {
			d.failed(w, r, "listing instances", err)
			return
		}
		out = append(out, v)
	}
	writeJSON(w, http.StatusOK, out)
}

// --- checks on what the operator sends ---

// validAddress reports whether raw is an https address with a host, without
// credentials, query, fragment or trailing slash, as the config demands.
func validAddress(raw string) bool {
	u, err := url.Parse(raw)
	return err == nil && u.Scheme == "https" && u.Host != "" && u.User == nil &&
		u.RawQuery == "" && u.Fragment == "" && !strings.HasSuffix(raw, "/")
}

// checkSecrets validates the values of secrets for the fields an instance of
// platform takes. msg is the 400's message, "" when they are fine.
func checkSecrets(platform, approver string, secrets map[string]string) (msg string) {
	allowed := secretFields(platform, approver)
	for _, field := range slices.Sorted(maps.Keys(secrets)) {
		if platform == config.PlatformGitLab && field == instances.FieldWebhookSecret {
			return msgWebhookGenerated
		}
		if !slices.Contains(allowed, field) {
			return fmt.Sprintf("%s is not a secret this instance takes; it takes %s", field, strings.Join(allowed, ", "))
		}
		if v := secrets[field]; strings.TrimSpace(v) == "" || len(v) > maxSecretBytes {
			return fmt.Sprintf("%s must not be empty, and at most 16 KiB", field)
		}
	}
	return ""
}

// redactSecrets replaces every secret of s found in text with [REDACTED]:
// an error from a platform can echo what it was sent.
func redactSecrets(text string, s instances.Secrets) string {
	for _, v := range s.Fields() {
		text = strings.ReplaceAll(text, v, "[REDACTED]")
	}
	return text
}

// secretsFromMap is the instances.Secrets holding the given fields.
func secretsFromMap(m map[string]string) instances.Secrets {
	return instances.Secrets{
		ReviewToken: m[instances.FieldReviewToken], ApproveToken: m[instances.FieldApproveToken],
		WebhookSecret: m[instances.FieldWebhookSecret],
		ReviewAppKey:  m[instances.FieldReviewAppKey], ApproveAppKey: m[instances.FieldApproveAppKey],
	}
}

// --- POST /api/admin/instances ---

func (d *Dashboard) addInstance(w http.ResponseWriter, r *http.Request) {
	se := session(r)
	var in struct {
		Name         string `json:"name"`
		Platform     string `json:"platform"`
		URL          string `json:"url"`
		APIURL       string `json:"apiURL"`
		ReviewAppID  int64  `json:"reviewAppID"`
		ApproveAppID int64  `json:"approveAppID"`
		// ApproveWithReviewBot is a GitLab instance's: its review bot
		// approves too, and it takes no approve_token.
		ApproveWithReviewBot bool              `json:"approveWithReviewBot"`
		Secrets              map[string]string `json:"secrets"`
	}
	if err := decodeStrict(r, &in); err != nil {
		writeError(w, http.StatusBadRequest, msgBadInstanceBody)
		return
	}
	if len(in.Name) > instanceNameLimit || !instanceNamePattern.MatchString(in.Name) {
		writeError(w, http.StatusBadRequest, msgBadInstanceName)
		return
	}
	if in.Platform != config.PlatformGitLab && in.Platform != config.PlatformGitHub {
		writeError(w, http.StatusBadRequest, msgBadPlatform)
		return
	}
	if _, taken := d.registry.Get(in.Name); taken {
		writeError(w, http.StatusConflict, msgInstanceTaken)
		return
	}
	if in.ApproveWithReviewBot && in.Platform != config.PlatformGitLab {
		writeError(w, http.StatusBadRequest, msgGitHubFields)
		return
	}
	row := store.InstanceRow{Name: in.Name, Platform: in.Platform, ApproveWithReviewBot: in.ApproveWithReviewBot}
	if msg := d.checkAddress(&row, in.URL, in.APIURL, in.ReviewAppID, in.ApproveAppID); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	secrets := in.Secrets
	if secrets == nil {
		secrets = map[string]string{}
	}
	if msg := checkSecrets(in.Platform, approverOfRow(row), secrets); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	if in.Platform == config.PlatformGitLab {
		hook, err := generateWebhookSecret()
		if err != nil {
			d.Log.Error("dashboard: generating a webhook secret failed", "error", err.Error())
			writeError(w, http.StatusInternalServerError, msgWriteFailed)
			return
		}
		secrets[instances.FieldWebhookSecret] = hook
	}
	for _, field := range secretFields(in.Platform, approverOfRow(row)) {
		if secrets[field] == "" {
			writeError(w, http.StatusBadRequest, field+" is required")
			return
		}
	}

	ctx, cancel := context.WithTimeout(r.Context(), operatorTimeout)
	defer cancel()
	inst := instances.FromRow(row)
	plain := secretsFromMap(secrets)
	if d.connector != nil {
		if err := d.connector.Check(ctx, inst, plain); err != nil {
			d.Log.Info("dashboard: an instance to add failed its check", "instance", in.Name, "by", se.Username,
				"error", redactSecrets(err.Error(), plain))
			writeError(w, http.StatusBadRequest, redactSecrets(err.Error(), plain))
			return
		}
	}
	err := d.Store.CreateInstance(ctx, row, d.seal(secrets), d.now())
	if errors.Is(err, store.ErrExists) {
		writeError(w, http.StatusConflict, msgInstanceTaken)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: adding an instance failed", "instance", in.Name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	d.registry.Put(inst)
	d.connect(ctx, inst, plain)
	d.Log.Info("dashboard: instance added", "instance", in.Name, "platform", in.Platform, "by", se.Username)
	d.audit(ctx, se, "instance_added", in.Name, "", in.Platform+" "+row.URL+row.APIURL)
	d.writeInstance(w, r, inst, http.StatusCreated)
}

// checkAddress fills row's address and App IDs from the request's, for its
// platform; msg is the 400's message, "" when they are fine.
func (d *Dashboard) checkAddress(row *store.InstanceRow, rawURL, apiURL string, reviewAppID, approveAppID int64) (msg string) {
	if row.Platform == config.PlatformGitLab {
		switch {
		case apiURL != "" || reviewAppID != 0 || approveAppID != 0:
			return msgGitLabFields
		case !validAddress(rawURL):
			return msgBadGitLabURL
		}
		row.URL = rawURL
		return ""
	}
	switch {
	case rawURL != "":
		return msgGitHubFields
	case !validAddress(apiURL):
		return msgBadAPIURL
	case reviewAppID <= 0 || approveAppID < 0:
		return msgBadAppIDs
	}
	row.APIURL, row.ReviewAppID, row.ApproveAppID = apiURL, reviewAppID, approveAppID
	return ""
}

// generateWebhookSecret is 32 random bytes in hex.
func generateWebhookSecret() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// seal seals each secret of the map.
func (d *Dashboard) seal(secrets map[string]string) map[string][]byte {
	out := make(map[string][]byte, len(secrets))
	for field, v := range secrets {
		out[field] = d.Auth.box.Seal([]byte(v))
	}
	return out
}

// AttInstanceUnreachable is the kind of the instance-wide "Needs attention"
// item recorded for an instance of the dashboard pergent.sh couldn't connect
// to. The connector clears it when it connects.
const AttInstanceUnreachable = "instance_unreachable"

// connect puts inst in use after it was stored. The credentials were just
// checked, so a failure now is a platform that went away meanwhile: it is
// logged and recorded as an "Needs attention" item (without the secrets),
// the instance stays stored and saving it again connects it.
func (d *Dashboard) connect(ctx context.Context, inst instances.Instance, s instances.Secrets) {
	if d.connector == nil {
		return
	}
	err := d.connector.Connect(ctx, inst, s)
	if err == nil {
		return
	}
	msg := redactSecrets(err.Error(), s)
	d.Log.Error("dashboard: couldn't connect an instance that passed its check; saving it again tries again",
		"instance", inst.Name, "error", msg)
	if err := d.Store.SetAttention(context.WithoutCancel(ctx), inst.Name, "", AttInstanceUnreachable, msg); err != nil {
		d.Log.Warn("dashboard: couldn't record that an instance is unreachable", "instance", inst.Name,
			"error", redactSecrets(err.Error(), s))
	}
}

// writeInstance answers with inst's view and status.
func (d *Dashboard) writeInstance(w http.ResponseWriter, r *http.Request, inst instances.Instance, status int) {
	v, err := d.instanceView(context.WithoutCancel(r.Context()), inst)
	if err != nil {
		d.failed(w, r, "describing an instance", err)
		return
	}
	writeJSON(w, status, v)
}

// --- PUT /api/admin/instances/{name} ---

func (d *Dashboard) updateInstance(w http.ResponseWriter, r *http.Request) {
	se, name := session(r), r.PathValue("name")
	inst, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if inst.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigInstance)
		return
	}
	if inst.Removing {
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	var in struct {
		Secrets map[string]string `json:"secrets"`
		// The address and App IDs can't change; they are read to be refused.
		URL          *string `json:"url"`
		APIURL       *string `json:"apiURL"`
		ReviewAppID  *int64  `json:"reviewAppID"`
		ApproveAppID *int64  `json:"approveAppID"`
	}
	if err := decodeStrict(r, &in); err != nil {
		writeError(w, http.StatusBadRequest, msgBadInstanceUpdate)
		return
	}
	if differs(in.URL, urlOf(inst)) || differs(in.APIURL, apiURLOf(inst)) ||
		differs(in.ReviewAppID, reviewAppIDOf(inst)) || differs(in.ApproveAppID, approveAppIDOf(inst)) {
		writeError(w, http.StatusBadRequest, msgImmutable)
		return
	}
	if len(in.Secrets) == 0 {
		writeError(w, http.StatusBadRequest, msgNothingToChange)
		return
	}
	if msg := checkSecrets(inst.Platform, approverOf(inst), in.Secrets); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), operatorTimeout)
	defer cancel()
	merged, _, err := d.registry.Secrets(ctx, name)
	if err != nil {
		d.Log.Error("dashboard: reading an instance's secrets failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	fields := merged.Fields()
	for field, v := range in.Secrets {
		fields[field] = v
	}
	merged = secretsFromMap(fields)
	if d.connector != nil {
		if err := d.connector.Check(ctx, inst, merged); err != nil {
			d.Log.Info("dashboard: an instance change failed its check", "instance", name, "by", se.Username,
				"error", redactSecrets(err.Error(), merged))
			writeError(w, http.StatusBadRequest, redactSecrets(err.Error(), merged))
			return
		}
	}
	found, err := d.Store.UpdateInstance(ctx, name, nil, d.seal(in.Secrets), d.now())
	if errors.Is(err, store.ErrRemoving) {
		// A removal landed while the credentials were being checked.
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: updating an instance failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	if !found {
		notFound(w)
		return
	}
	// A removal that lands now keeps its Removing.
	cur, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if cur.Removing {
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	d.connect(ctx, cur, merged)

	changed := slices.Sorted(maps.Keys(in.Secrets))
	d.Log.Info("dashboard: instance updated", "instance", name, "fields", changed, "by", se.Username)
	d.audit(ctx, se, "instance_updated", name, "", strings.Join(changed, ", "))
	d.writeInstance(w, r, cur, http.StatusOK)
}

// putInstanceTrust sets a dashboard instance's trusted-authors mode, the
// default of its repositories: 204, or 409 for a config instance (its mode is
// in the config file) or one being removed.
func (d *Dashboard) putInstanceTrust(w http.ResponseWriter, r *http.Request) {
	se, name := session(r), r.PathValue("name")
	inst, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if inst.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigInstance)
		return
	}
	var in struct {
		Mode string `json:"mode"`
	}
	if err := decodeStrict(r, &in); err != nil ||
		(in.Mode != config.TrustFollowVisibility && in.Mode != config.TrustOn && in.Mode != config.TrustOff) {
		writeError(w, http.StatusBadRequest, msgBadTrustMode)
		return
	}
	ctx := r.Context()
	found, err := d.Store.SetInstanceTrustMode(ctx, name, in.Mode)
	if errors.Is(err, store.ErrRemoving) {
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: setting an instance's trusted authors failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	if !found {
		notFound(w)
		return
	}
	d.registry.SetTrustMode(name, in.Mode)
	d.Log.Info("dashboard: instance updated", "instance", name, "trusted_authors_only", in.Mode, "by", se.Username)
	d.audit(ctx, se, "instance_updated", name, "", "trusted_authors_only="+in.Mode)
	w.WriteHeader(http.StatusNoContent)
}

func urlOf(inst instances.Instance) string {
	if inst.GitLab != nil {
		return inst.GitLab.URL
	}
	return ""
}

func apiURLOf(inst instances.Instance) string {
	if inst.GitHub != nil {
		return inst.GitHub.APIURL
	}
	return ""
}

func reviewAppIDOf(inst instances.Instance) int64 {
	if inst.GitHub != nil {
		return inst.GitHub.ReviewApp.AppID
	}
	return 0
}

// approveAppIDOf is the approve App's ID in the row's terms: 0 for a token,
// the review App's own ID when it approves.
func approveAppIDOf(inst instances.Instance) int64 {
	if inst.GitHub == nil {
		return 0
	}
	switch inst.GitHub.Approver() {
	case config.ApproverReviewApp:
		return inst.GitHub.ReviewApp.AppID
	case config.ApproverApp:
		return inst.GitHub.ApproveApp.AppID
	}
	return 0
}

// differs reports whether a value given in a request is there and not the
// current one.
func differs[T comparable](given *T, current T) bool { return given != nil && *given != current }

// --- DELETE /api/admin/instances/{name} ---

func (d *Dashboard) removeInstance(w http.ResponseWriter, r *http.Request) {
	ctx, se, name := r.Context(), session(r), r.PathValue("name")
	inst, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if inst.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigInstance)
		return
	}
	fail := func(what string, err error) {
		d.Log.Error("dashboard: removing an instance failed; removing it again continues", "instance", name, "step", what, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
	}

	// The projects the engine takes off the platform: the repositories
	// switched on, which are about to be switched off, and those stored.
	var keys []RepoKey
	rows, err := d.Store.DashboardRepos(ctx)
	if err != nil {
		fail("listing repositories", err)
		return
	}
	for _, row := range rows {
		if row.Instance == name {
			keys = append(keys, RepoKey{Instance: name, Path: row.Project})
		}
	}
	projects, err := d.Store.Projects(ctx)
	if err != nil {
		fail("listing projects", err)
		return
	}
	for _, p := range projects {
		if p.Instance == name && !slices.ContainsFunc(keys, func(k RepoKey) bool { return strings.EqualFold(k.Path, p.Path) }) {
			keys = append(keys, RepoKey{Instance: name, Path: p.Path})
		}
	}

	found, err := d.Store.MarkInstanceRemoving(ctx, name)
	if err != nil {
		fail("marking it", err)
		return
	}
	if !found {
		notFound(w)
		return
	}
	d.registry.SetRemoving(name)
	if _, err := d.Store.SupersedeInstance(ctx, name); err != nil {
		fail("superseding its runs", err)
		return
	}
	if err := d.Store.DeleteInstanceData(ctx, name); err != nil {
		fail("deleting its accounts and repositories", err)
		return
	}
	// The engine takes the webhooks off the platform and then deletes the
	// instance. With no project to take off it still needs a pass.
	if len(keys) == 0 {
		keys = append(keys, RepoKey{Instance: name})
	}
	for _, k := range keys {
		d.reconcileSoon(k.Instance, k.Path)
	}
	d.Log.Info("dashboard: instance being removed", "instance", name, "by", se.Username)
	d.audit(ctx, se, "instance_removed", name, "", "")
	writeJSON(w, http.StatusAccepted, map[string]string{"status": "removing"})
}

