const (
	// operatorTimeout bounds an instance add or change: the check and the
	// connection each reach the platform, and the answer must be written
	// well before the server's 60 s WriteTimeout.
	operatorTimeout = 40 * time.Second
	// maxSecretBytes bounds one secret (a GitHub App private key is about
	// 1.7 KB).
	maxSecretBytes = 16 << 10
	maxInstanceID  = 256
	maxLLMField    = 256

	msgBadInstanceBody   = `the body must be {"name": ..., "platform": "gitlab" or "github", "url" (GitLab) or "apiURL" and "reviewAppID" (GitHub), "oauthClientID": ..., "secrets": {...}}`
	msgBadInstanceUpdate = `the body must be {"oauthClientID": ..., "secrets": {...}}`
	msgBadInstanceName   = `the name must be 1 to 63 lowercase letters, digits or "-"`
	msgBadPlatform       = `platform must be "gitlab" or "github"`
	msgInstanceTaken     = "an instance with this name exists already, in the config file or the dashboard"
	msgBadGitLabURL      = "url must be the https address of the GitLab server, without a trailing slash"
	msgBadAPIURL         = "apiURL must be the https address of the GitHub API, without a trailing slash"
	msgGitLabFields      = "a GitLab instance takes a url, not apiURL or App IDs"
	msgGitHubFields      = "a GitHub instance takes apiURL, reviewAppID and approveAppID, not url"
	msgBadAppIDs         = "reviewAppID must be positive, and approveAppID 0 (a bot user's token approves) or positive and different from reviewAppID"
	msgWebhookGenerated  = "a GitLab instance's webhook_secret is generated by pergent.sh: don't send one"
	msgOAuthPair         = "oauthClientID and oauth_client_secret go together: give both, or neither"
	msgBadOAuthID        = "oauthClientID must be at most 256 characters without spaces"
	msgImmutable         = "an instance's address and App IDs can't change: remove it and add it again"
	msgConfigInstance    = "this instance is managed by the config file; change it there"
	msgInstanceRemoving  = "this instance is being removed"
	msgNothingToChange   = `nothing to change: give "oauthClientID" or "secrets"`

	msgBadLLMBody     = `the body must be {"provider": ..., "model": ..., "baseURL": ..., "apiKey": ...}`
	msgLLMRequired    = "provider and model are required, each at most 256 characters"
	msgBadBaseURL     = "baseURL must be empty or an absolute http or https URL"
	msgKeyRequired    = "apiKey is required: none is stored"
	msgConfigLLM      = "the LLM is set in the config file; change it there"
	msgBadDefaults    = "the body must be a JSON object of defaults: approve, reviewDrafts, failureStatus, jobTimeoutSeconds, jobMemory"
	instanceNameLimit = 63
)

var instanceNamePattern = regexp.MustCompile(`^[a-z0-9-]+$`)

// operatorRoutes adds the instances, LLM and defaults API to mux, every
// route behind Auth.Require (which checks X-CSRF-Token on writes): the
// instances for operators only, the LLM and the defaults readable by admins
// and writable by operators and admins respectively.
func (d *Dashboard) operatorRoutes(mux *http.ServeMux) {
	operator := func(pattern string, h http.HandlerFunc) { mux.Handle(pattern, d.Auth.Require(requireOperator(h))) }
	admin := func(pattern string, h http.HandlerFunc) { mux.Handle(pattern, d.Auth.Require(requireAdmin(h))) }
	operator("GET /api/admin/instances", d.listInstances)
	operator("POST /api/admin/instances", d.addInstance)
	operator("PUT /api/admin/instances/{name}", d.updateInstance)
	operator("DELETE /api/admin/instances/{name}", d.removeInstance)
	operator("GET /api/admin/instances/{name}/repositories", d.instanceRepositories)
	admin("GET /api/admin/llm", d.getLLM)
	operator("PUT /api/admin/llm", d.putLLM)
	admin("GET /api/admin/defaults", d.getDefaults)
	admin("PUT /api/admin/defaults", d.putDefaults)
}

// --- views ---

// secretFields are the secrets an instance takes, in the order they are shown.
func secretFields(platform string, approveApp bool) []string {
	if platform == config.PlatformGitLab {
		return []string{instances.FieldReviewToken, instances.FieldApproveToken, instances.FieldWebhookSecret, instances.FieldOAuthClientSecret}
	}
	approve := instances.FieldApproveToken
	if approveApp {
		approve = instances.FieldApproveAppKey
	}
	return []string{instances.FieldReviewAppKey, approve, instances.FieldWebhookSecret, instances.FieldOAuthClientSecret}
}

// configEnvs maps each secret field of a config instance to the env var
// holding it.
func configEnvs(inst instances.Instance) map[string]string {
	switch {
	case inst.GitLab != nil:
		g := inst.GitLab
		return map[string]string{
			instances.FieldReviewToken: g.ReviewTokenEnv, instances.FieldApproveToken: g.ApproveTokenEnv,
			instances.FieldWebhookSecret: g.WebhookSecretEnv, instances.FieldOAuthClientSecret: g.OAuthClientSecretEnv,
		}
	case inst.GitHub != nil:
		g := inst.GitHub
		out := map[string]string{
			instances.FieldReviewAppKey: g.ReviewApp.PrivateKeyEnv, instances.FieldApproveToken: g.ApproveTokenEnv,
			instances.FieldWebhookSecret: g.WebhookSecretEnv, instances.FieldOAuthClientSecret: g.OAuthClientSecretEnv,
		}
		if g.ApproveApp != nil {
			out[instances.FieldApproveAppKey] = g.ApproveApp.PrivateKeyEnv
		}
		return out
	}
	return nil
}

// lookupEnv reports whether the env var name holds a value.
func lookupEnv(name string) bool { return name != "" && os.Getenv(name) != "" }

// approveApp reports whether inst approves with a GitHub App.
func approveApp(inst instances.Instance) bool {
	return inst.GitHub != nil && inst.GitHub.ApproveApp != nil
}

// instanceView describes inst. A config instance's secrets are set when the
// env var holds a value; a dashboard instance's when the sealed value opens.
func (d *Dashboard) instanceView(ctx context.Context, inst instances.Instance) (InstanceAdminView, error) {
	v := InstanceAdminView{Name: inst.Name, Platform: inst.Platform, Source: string(inst.Source), Removing: inst.Removing,
		Approver: approverKindToken, OAuthClientID: inst.OAuthClientID, Secrets: map[string]SecretView{}}
	switch {
	case inst.GitLab != nil:
		v.URL = inst.GitLab.URL
	case inst.GitHub != nil:
		v.APIURL, v.ReviewAppID = inst.GitHub.APIURL, inst.GitHub.ReviewApp.AppID
		if inst.GitHub.ApproveApp != nil {
			v.ApproveAppID, v.Approver = inst.GitHub.ApproveApp.AppID, approverKindApp
		}
	}
	fields := secretFields(inst.Platform, approveApp(inst))
	if inst.Source == instances.SourceConfig {
		envs := configEnvs(inst)
		for _, f := range fields {
			v.Secrets[f] = SecretView{Set: lookupEnv(envs[f])}
		}
		return v, nil
	}
	sealed, err := d.Store.InstanceSecrets(ctx, inst.Name)
	if err != nil {
		return InstanceAdminView{}, err
	}
	for _, f := range fields {
		sv := SecretView{}
		if s, ok := sealed[f]; ok {
			if plain, err := d.Auth.box.Open(s.Value); err == nil && len(plain) > 0 {
				at := s.UpdatedAt
				sv = SecretView{Set: true, UpdatedAt: &at}
			}
		}
		v.Secrets[f] = sv
	}
	return v, nil
}

func (d *Dashboard) listInstances(w http.ResponseWriter, r *http.Request) {
	all := d.registry.All()
	out := make([]InstanceAdminView, 0, len(all))
	for _, inst := range all {
		v, err := d.instanceView(r.Context(), inst)
		if err != nil {
			d.failed(w, r, "listing instances", err)
			return
		}
		out = append(out, v)
	}
	writeJSON(w, http.StatusOK, out)
}

// --- checks on what the operator sends ---

// validAddress reports whether raw is an https address with a host, without
// credentials, query, fragment or trailing slash, as the config demands.
func validAddress(raw string) bool {
	u, err := url.Parse(raw)
	return err == nil && u.Scheme == "https" && u.Host != "" && u.User == nil &&
		u.RawQuery == "" && u.Fragment == "" && !strings.HasSuffix(raw, "/")
}

// validOAuthID reports whether id can be an OAuth client ID.
func validOAuthID(id string) bool {
	return len(id) <= maxInstanceID && !strings.ContainsAny(id, " \t\r\n")
}

// checkSecrets validates the values of secrets for the fields an instance of
// platform takes. msg is the 400's message, "" when they are fine.
func checkSecrets(platform string, withApproveApp bool, secrets map[string]string) (msg string) {
	allowed := secretFields(platform, withApproveApp)
	for _, field := range slices.Sorted(maps.Keys(secrets)) {
		if platform == config.PlatformGitLab && field == instances.FieldWebhookSecret {
			return msgWebhookGenerated
		}
		if !slices.Contains(allowed, field) {
			return fmt.Sprintf("%s is not a secret this instance takes; it takes %s", field, strings.Join(allowed, ", "))
		}
		if v := secrets[field]; strings.TrimSpace(v) == "" || len(v) > maxSecretBytes {
			return fmt.Sprintf("%s must not be empty, and at most 16 KiB", field)
		}
	}
	return ""
}

// redactSecrets replaces every secret of s found in text with [REDACTED]:
// an error from a platform can echo what it was sent.
func redactSecrets(text string, s instances.Secrets) string {
	for _, v := range s.Fields() {
		text = strings.ReplaceAll(text, v, "[REDACTED]")
	}
	return text
}

// secretsFromMap is the instances.Secrets holding the given fields.
func secretsFromMap(m map[string]string) instances.Secrets {
	return instances.Secrets{
		ReviewToken: m[instances.FieldReviewToken], ApproveToken: m[instances.FieldApproveToken],
		WebhookSecret: m[instances.FieldWebhookSecret], OAuthClientSecret: m[instances.FieldOAuthClientSecret],
		ReviewAppKey: m[instances.FieldReviewAppKey], ApproveAppKey: m[instances.FieldApproveAppKey],
	}
}

// --- POST /api/admin/instances ---

func (d *Dashboard) addInstance(w http.ResponseWriter, r *http.Request) {
	se := session(r)
	var in struct {
		Name          string            `json:"name"`
		Platform      string            `json:"platform"`
		URL           string            `json:"url"`
		APIURL        string            `json:"apiURL"`
		ReviewAppID   int64             `json:"reviewAppID"`
		ApproveAppID  int64             `json:"approveAppID"`
		OAuthClientID string            `json:"oauthClientID"`
		Secrets       map[string]string `json:"secrets"`
	}
	if err := decodeStrict(r, &in); err != nil {
		writeError(w, http.StatusBadRequest, msgBadInstanceBody)
		return
	}
	if len(in.Name) > instanceNameLimit || !instanceNamePattern.MatchString(in.Name) {
		writeError(w, http.StatusBadRequest, msgBadInstanceName)
		return
	}
	if in.Platform != config.PlatformGitLab && in.Platform != config.PlatformGitHub {
		writeError(w, http.StatusBadRequest, msgBadPlatform)
		return
	}
	if _, taken := d.registry.Get(in.Name); taken {
		writeError(w, http.StatusConflict, msgInstanceTaken)
		return
	}
	row := store.InstanceRow{Name: in.Name, Platform: in.Platform, OAuthClientID: in.OAuthClientID}
	if msg := d.checkAddress(&row, in.URL, in.APIURL, in.ReviewAppID, in.ApproveAppID); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	if !validOAuthID(in.OAuthClientID) {
		writeError(w, http.StatusBadRequest, msgBadOAuthID)
		return
	}
	secrets := in.Secrets
	if secrets == nil {
		secrets = map[string]string{}
	}
	if msg := checkSecrets(in.Platform, row.ApproveAppID != 0, secrets); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	if in.Platform == config.PlatformGitLab {
		hook, err := generateWebhookSecret()
		if err != nil {
			d.Log.Error("dashboard: generating a webhook secret failed", "error", err.Error())
			writeError(w, http.StatusInternalServerError, msgWriteFailed)
			return
		}
		secrets[instances.FieldWebhookSecret] = hook
	}
	for _, field := range secretFields(in.Platform, row.ApproveAppID != 0) {
		if field == instances.FieldOAuthClientSecret {
			continue
		}
		if secrets[field] == "" {
			writeError(w, http.StatusBadRequest, field+" is required")
			return
		}
	}
	if (in.OAuthClientID == "") != (secrets[instances.FieldOAuthClientSecret] == "") {
		writeError(w, http.StatusBadRequest, msgOAuthPair)
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), operatorTimeout)
	defer cancel()
	inst := instances.FromRow(row)
	plain := secretsFromMap(secrets)
	if d.connector != nil {
		if err := d.connector.Check(ctx, inst, plain); err != nil {
			d.Log.Info("dashboard: an instance to add failed its check", "instance", in.Name, "by", se.Username,
				"error", redactSecrets(err.Error(), plain))
			writeError(w, http.StatusBadRequest, redactSecrets(err.Error(), plain))
			return
		}
	}
	err := d.Store.CreateInstance(ctx, row, d.seal(secrets), d.now())
	if errors.Is(err, store.ErrExists) {
		writeError(w, http.StatusConflict, msgInstanceTaken)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: adding an instance failed", "instance", in.Name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	d.registry.Put(inst)
	d.connect(ctx, inst, plain)
	d.Log.Info("dashboard: instance added", "instance", in.Name, "platform", in.Platform, "by", se.Username)
	d.audit(ctx, se, "instance_added", in.Name, "", in.Platform+" "+row.URL+row.APIURL)
	d.writeInstance(w, r, inst, http.StatusCreated)
}

// checkAddress fills row's address and App IDs from the request's, for its
// platform; msg is the 400's message, "" when they are fine.
func (d *Dashboard) checkAddress(row *store.InstanceRow, rawURL, apiURL string, reviewAppID, approveAppID int64) (msg string) {
	if row.Platform == config.PlatformGitLab {
		switch {
		case apiURL != "" || reviewAppID != 0 || approveAppID != 0:
			return msgGitLabFields
		case !validAddress(rawURL):
			return msgBadGitLabURL
		}
		row.URL = rawURL
		return ""
	}
	switch {
	case rawURL != "":
		return msgGitHubFields
	case !validAddress(apiURL):
		return msgBadAPIURL
	case reviewAppID <= 0 || approveAppID < 0 || approveAppID == reviewAppID:
		return msgBadAppIDs
	}
	row.APIURL, row.ReviewAppID, row.ApproveAppID = apiURL, reviewAppID, approveAppID
	return ""
}

// generateWebhookSecret is 32 random bytes in hex.
func generateWebhookSecret() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// seal seals each secret of the map.
func (d *Dashboard) seal(secrets map[string]string) map[string][]byte {
	out := make(map[string][]byte, len(secrets))
	for field, v := range secrets {
		out[field] = d.Auth.box.Seal([]byte(v))
	}
	return out
}

// AttInstanceUnreachable is the kind of the instance-wide "Needs attention"
// item recorded for an instance of the dashboard pergent.sh couldn't connect
// to. The connector clears it when it connects.
const AttInstanceUnreachable = "instance_unreachable"

// connect puts inst in use after it was stored. The credentials were just
// checked, so a failure now is a platform that went away meanwhile: it is
// logged and recorded as an "Needs attention" item (without the secrets),
// the instance stays stored and saving it again connects it.
func (d *Dashboard) connect(ctx context.Context, inst instances.Instance, s instances.Secrets) {
	if d.connector == nil {
		return
	}
	err := d.connector.Connect(ctx, inst, s)
	if err == nil {
		return
	}
	msg := redactSecrets(err.Error(), s)
	d.Log.Error("dashboard: couldn't connect an instance that passed its check; saving it again tries again",
		"instance", inst.Name, "error", msg)
	if err := d.Store.SetAttention(context.WithoutCancel(ctx), inst.Name, "", AttInstanceUnreachable, msg); err != nil {
		d.Log.Warn("dashboard: couldn't record that an instance is unreachable", "instance", inst.Name,
			"error", redactSecrets(err.Error(), s))
	}
}

// writeInstance answers with inst's view and status.
func (d *Dashboard) writeInstance(w http.ResponseWriter, r *http.Request, inst instances.Instance, status int) {
	v, err := d.instanceView(context.WithoutCancel(r.Context()), inst)
	if err != nil {
		d.failed(w, r, "describing an instance", err)
		return
	}
	writeJSON(w, status, v)
}

// --- PUT /api/admin/instances/{name} ---

func (d *Dashboard) updateInstance(w http.ResponseWriter, r *http.Request) {
	se, name := session(r), r.PathValue("name")
	inst, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if inst.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigInstance)
		return
	}
	if inst.Removing {
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	var in struct {
		OAuthClientID *string           `json:"oauthClientID"`
		Secrets       map[string]string `json:"secrets"`
		// The address and App IDs can't change; they are read to be refused.
		URL          *string `json:"url"`
		APIURL       *string `json:"apiURL"`
		ReviewAppID  *int64  `json:"reviewAppID"`
		ApproveAppID *int64  `json:"approveAppID"`
	}
	if err := decodeStrict(r, &in); err != nil {
		writeError(w, http.StatusBadRequest, msgBadInstanceUpdate)
		return
	}
	if differs(in.URL, urlOf(inst)) || differs(in.APIURL, apiURLOf(inst)) ||
		differs(in.ReviewAppID, reviewAppIDOf(inst)) || differs(in.ApproveAppID, approveAppIDOf(inst)) {
		writeError(w, http.StatusBadRequest, msgImmutable)
		return
	}
	if in.OAuthClientID == nil && len(in.Secrets) == 0 {
		writeError(w, http.StatusBadRequest, msgNothingToChange)
		return
	}
	if msg := checkSecrets(inst.Platform, approveApp(inst), in.Secrets); msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	clientID := inst.OAuthClientID
	if in.OAuthClientID != nil {
		clientID = *in.OAuthClientID
		if !validOAuthID(clientID) {
			writeError(w, http.StatusBadRequest, msgBadOAuthID)
			return
		}
	}

	ctx, cancel := context.WithTimeout(r.Context(), operatorTimeout)
	defer cancel()
	merged, _, err := d.registry.Secrets(ctx, name)
	if err != nil {
		d.Log.Error("dashboard: reading an instance's secrets failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	fields := merged.Fields()
	for field, v := range in.Secrets {
		fields[field] = v
	}
	merged = secretsFromMap(fields)
	if clientID != "" && merged.OAuthClientSecret == "" {
		writeError(w, http.StatusBadRequest, msgOAuthPair)
		return
	}
	next := inst
	next.OAuthClientID = clientID
	if d.connector != nil {
		if err := d.connector.Check(ctx, next, merged); err != nil {
			d.Log.Info("dashboard: an instance change failed its check", "instance", name, "by", se.Username,
				"error", redactSecrets(err.Error(), merged))
			writeError(w, http.StatusBadRequest, redactSecrets(err.Error(), merged))
			return
		}
	}
	found, err := d.Store.UpdateInstance(ctx, name, in.OAuthClientID, d.seal(in.Secrets), d.now())
	if errors.Is(err, store.ErrRemoving) {
		// A removal landed while the credentials were being checked.
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: updating an instance failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	if !found {
		notFound(w)
		return
	}
	// Changed in place: a removal that lands now keeps its Removing.
	cur, ok := d.registry.SetOAuthClientID(name, clientID)
	if !ok {
		notFound(w)
		return
	}
	if cur.Removing {
		writeError(w, http.StatusConflict, msgInstanceRemoving)
		return
	}
	d.connect(ctx, cur, merged)
	if after, _ := d.registry.Get(name); after.Removing {
		// Removed while it was being connected: no sign-in comes back.
		d.Auth.RemoveProvider(name)
	}

	changed := slices.Sorted(maps.Keys(in.Secrets))
	if in.OAuthClientID != nil && clientID != inst.OAuthClientID {
		changed = append([]string{"oauth_client_id"}, changed...)
	}
	d.Log.Info("dashboard: instance updated", "instance", name, "fields", changed, "by", se.Username)
	d.audit(ctx, se, "instance_updated", name, "", strings.Join(changed, ", "))
	d.writeInstance(w, r, cur, http.StatusOK)
}

func urlOf(inst instances.Instance) string {
	if inst.GitLab != nil {
		return inst.GitLab.URL
	}
	return ""
}

func apiURLOf(inst instances.Instance) string {
	if inst.GitHub != nil {
		return inst.GitHub.APIURL
	}
	return ""
}

func reviewAppIDOf(inst instances.Instance) int64 {
	if inst.GitHub != nil {
		return inst.GitHub.ReviewApp.AppID
	}
	return 0
}

func approveAppIDOf(inst instances.Instance) int64 {
	if inst.GitHub != nil && inst.GitHub.ApproveApp != nil {
		return inst.GitHub.ApproveApp.AppID
	}
	return 0
}

// differs reports whether a value given in a request is there and not the
// current one.
func differs[T comparable](given *T, current T) bool { return given != nil && *given != current }

// --- DELETE /api/admin/instances/{name} ---

func (d *Dashboard) removeInstance(w http.ResponseWriter, r *http.Request) {
	ctx, se, name := r.Context(), session(r), r.PathValue("name")
	inst, ok := d.registry.Get(name)
	if !ok {
		notFound(w)
		return
	}
	if inst.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigInstance)
		return
	}
	fail := func(what string, err error) {
		d.Log.Error("dashboard: removing an instance failed; removing it again continues", "instance", name, "step", what, "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
	}

	// The projects the engine takes off the platform: the repositories
	// switched on, which are about to be switched off, and those stored.
	var keys []RepoKey
	rows, err := d.Store.DashboardRepos(ctx)
	if err != nil {
		fail("listing repositories", err)
		return
	}
	for _, row := range rows {
		if row.Instance == name {
			keys = append(keys, RepoKey{Instance: name, Path: row.Project})
		}
	}
	projects, err := d.Store.Projects(ctx)
	if err != nil {
		fail("listing projects", err)
		return
	}
	for _, p := range projects {
		if p.Instance == name && !slices.ContainsFunc(keys, func(k RepoKey) bool { return strings.EqualFold(k.Path, p.Path) }) {
			keys = append(keys, RepoKey{Instance: name, Path: p.Path})
		}
	}

	found, err := d.Store.MarkInstanceRemoving(ctx, name)
	if err != nil {
		fail("marking it", err)
		return
	}
	if !found {
		notFound(w)
		return
	}
	d.registry.SetRemoving(name)
	// Nobody signs in through it from here on; people already signed in
	// lose their sessions with their accounts below.
	d.Auth.RemoveProvider(name)
	if _, err := d.Store.SupersedeInstance(ctx, name); err != nil {
		fail("superseding its runs", err)
		return
	}
	if err := d.Store.DeleteInstanceData(ctx, name); err != nil {
		fail("deleting its accounts and repositories", err)
		return
	}
	// The engine takes the webhooks off the platform and then deletes the
	// instance. With no project to take off it still needs a pass.
	if len(keys) == 0 {
		keys = append(keys, RepoKey{Instance: name})
	}
	for _, k := range keys {
		d.reconcileSoon(k.Instance, k.Path)
	}
	d.Log.Info("dashboard: instance being removed", "instance", name, "by", se.Username)
	d.audit(ctx, se, "instance_removed", name, "", "")
	writeJSON(w, http.StatusAccepted, map[string]string{"status": "removing"})
}

// --- GET /api/admin/instances/{name}/repositories ---

func (d *Dashboard) instanceRepositories(w http.ResponseWriter, r *http.Request) {
	name := r.PathValue("name")
	if inst, ok := d.registry.Get(name); !ok || inst.Removing {
		notFound(w)
		return
	}
	search := strings.TrimSpace(r.URL.Query().Get("search"))
	if len(search) > maxSearch {
		writeError(w, http.StatusBadRequest, "search must be at most 100 characters")
		return
	}
	ctx, cancel := context.WithTimeoutCause(r.Context(), d.availableBudget, errOutOfBudget)
	defer cancel()
	all, err := d.Repos.List(ctx)
	if err != nil {
		d.failed(w, r, "listing repositories", err)
		return
	}
	on := map[string]bool{}
	for _, e := range all {
		if e.Instance == name {
			on[lower(e.Project)] = true
		}
	}
	repos, truncated, err := d.catalogRepos(ctx, name, search)
	if err != nil {
		d.Log.Warn("dashboard: listing the repositories that can be switched on failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusBadGateway, msgListFailed)
		return
	}
	platform, _ := d.registry.Platform(name)
	view := AvailableView{Items: []AvailableRepo{}, Truncated: truncated}
	sorted := slices.Clone(repos)
	sort.Strings(sorted)
	for _, p := range sorted {
		if on[lower(p)] {
			continue
		}
		if len(view.Items) == maxAvailable {
			view.Truncated = true
			break
		}
		view.Items = append(view.Items, AvailableRepo{Instance: name, Project: p, Platform: platform})
	}
	writeJSON(w, http.StatusOK, view)
}

// --- the LLM ---

func (d *Dashboard) llmView(se Session) LLMAdminView {
	st := d.registry.LLMStatus()
	v := LLMAdminView{Source: string(st.Source), Provider: st.LLM.Provider, Model: st.LLM.Model, BaseURL: st.LLM.BaseURL,
		Key: SecretView{Set: st.KeySet}, Editable: se.Operator && st.Source == instances.SourceDashboard}
	if st.KeySet && !st.UpdatedAt.IsZero() {
		at := st.UpdatedAt
		v.Key.UpdatedAt = &at
	}
	return v
}

func (d *Dashboard) getLLM(w http.ResponseWriter, r *http.Request) {
	writeJSON(w, http.StatusOK, d.llmView(session(r)))
}

func (d *Dashboard) putLLM(w http.ResponseWriter, r *http.Request) {
	ctx, se := r.Context(), session(r)
	before := d.registry.LLMStatus()
	if before.Source == instances.SourceConfig {
		writeError(w, http.StatusConflict, msgConfigLLM)
		return
	}
	var in struct {
		Provider string  `json:"provider"`
		Model    string  `json:"model"`
		BaseURL  string  `json:"baseURL"`
		APIKey   *string `json:"apiKey"`
	}
	if err := decodeStrict(r, &in); err != nil {
		writeError(w, http.StatusBadRequest, msgBadLLMBody)
		return
	}
	in.Provider, in.Model, in.BaseURL = strings.TrimSpace(in.Provider), strings.TrimSpace(in.Model), strings.TrimSpace(in.BaseURL)
	if in.Provider == "" || in.Model == "" || len(in.Provider) > maxLLMField || len(in.Model) > maxLLMField {
		writeError(w, http.StatusBadRequest, msgLLMRequired)
		return
	}
	if in.BaseURL != "" {
		u, err := url.Parse(in.BaseURL)
		if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || u.User != nil || len(in.BaseURL) > 2048 {
			writeError(w, http.StatusBadRequest, msgBadBaseURL)
			return
		}
	}
	var sealed []byte
	switch {
	case in.APIKey != nil:
		if strings.TrimSpace(*in.APIKey) == "" || len(*in.APIKey) > maxSecretBytes {
			writeError(w, http.StatusBadRequest, "apiKey must not be empty, and at most 16 KiB")
			return
		}
		sealed = d.Auth.box.Seal([]byte(*in.APIKey))
	case !before.KeySet:
		writeError(w, http.StatusBadRequest, msgKeyRequired)
		return
	}
	if err := d.Store.PutLLM(ctx, in.Provider, in.Model, in.BaseURL, sealed, d.now()); err != nil {
		d.Log.Error("dashboard: saving the LLM failed", "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	loadErr := d.loadLLM(ctx)
	var changed []string
	for _, f := range []struct{ name, before, after string }{
		{"provider", before.LLM.Provider, in.Provider}, {"model", before.LLM.Model, in.Model}, {"base_url", before.LLM.BaseURL, in.BaseURL},
	} {
		if f.before != f.after {
			changed = append(changed, f.name)
		}
	}
	if in.APIKey != nil {
		changed = append(changed, "api_key")
	}
	d.Log.Info("dashboard: LLM updated", "fields", changed, "by", se.Username)
	d.audit(ctx, se, "llm_updated", "", "", strings.Join(changed, ", "))
	if loadErr != nil {
		// Saved, but not read back: the engine uses the earlier LLM until
		// pergent.sh restarts or the LLM is saved again. The change is not
		// lost, so the answer is the saved one.
		msg := loadErr.Error()
		if in.APIKey != nil {
			msg = strings.ReplaceAll(msg, *in.APIKey, "[REDACTED]")
		}
		d.Log.Error("dashboard: the LLM was saved but reading it back failed; saving it again tries again", "error", msg)
		at := d.now()
		writeJSON(w, http.StatusOK, LLMAdminView{Source: string(instances.SourceDashboard), Provider: in.Provider, Model: in.Model,
			BaseURL: in.BaseURL, Key: SecretView{Set: true, UpdatedAt: &at}, Editable: se.Operator})
		return
	}
	writeJSON(w, http.StatusOK, d.llmView(se))
}

