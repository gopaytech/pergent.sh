// listAvailable answers with one page of the repositories of the instance
// called name that the review bot or App can set up and that aren't switched
// on: 404 for an instance that is not there or is being removed, 400 for a
// bad page. It serves the picker (GET /api/repositories/available?instance=)
// and GET /api/admin/instances/{name}/repositories.
//
// A catalog that pages on the platform (PagedRepoCatalog, GitLab) is asked for
// the one page, in the platform's order (by ID), which is sorted within the
// page. Another is read whole, kept 5 minutes, sorted, and served 50 at a time
// (a page is cut before the repositories switched on are dropped from it).
func (d *Dashboard) listAvailable(w http.ResponseWriter, r *http.Request, name string) {
	if inst, ok := d.registry.Get(name); !ok || inst.Removing {
		notFound(w)
		return
	}
	search := strings.TrimSpace(r.URL.Query().Get("search"))
	if len(search) > maxSearch {
		writeError(w, http.StatusBadRequest, "search must be at most 100 characters")
		return
	}
	page := 1
	if v := r.URL.Query().Get("page"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil || n < 1 || n > maxAvailablePage {
			writeError(w, http.StatusBadRequest, msgBadPage)
			return
		}
		page = n
	}
	ctx, cancel := context.WithTimeoutCause(r.Context(), d.availableBudget, errOutOfBudget)
	defer cancel()
	all, err := d.Repos.List(ctx)
	if err != nil {
		d.failed(w, r, "listing repositories", err)
		return
	}
	on := map[string]bool{}
	for _, e := range all {
		if e.Instance == name {
			on[lower(e.Project)] = true
		}
	}
	platform, _ := d.registry.Platform(name)
	view := AvailableView{Items: []AvailableRepo{}, Page: page}
	add := func(p string) {
		view.Items = append(view.Items, AvailableRepo{Instance: name, Project: p, Platform: platform})
	}

	if cat, ok := d.catalogs.Get(name); ok {
		if paged, ok := cat.(PagedRepoCatalog); ok {
			repos, hasMore, err := d.catalogPage(ctx, paged, name, search, page)
			if err != nil {
				d.Log.Warn("dashboard: listing the repositories that can be switched on failed", "instance", name, "error", err.Error())
				writeError(w, http.StatusBadGateway, msgListFailed)
				return
			}
			var off []string
			for _, p := range repos {
				if !on[lower(p)] {
					off = append(off, p)
				}
			}
			// The platform pages by ID, so no project falls between two
			// pages; each page is sorted by path for display.
			sort.Strings(off)
			for _, p := range off {
				add(p)
			}
			view.HasMore = hasMore
			writeJSON(w, http.StatusOK, view)
			return
		}
	}

	repos, truncated, err := d.catalogRepos(ctx, name, search)
	if err != nil {
		d.Log.Warn("dashboard: listing the repositories that can be switched on failed", "instance", name, "error", err.Error())
		writeError(w, http.StatusBadGateway, msgListFailed)
		return
	}
	// The pages are cut from the sorted list as it is, and the switched-on
	// repositories are dropped from each page after, as on GitLab: a
	// repository switched on between two Load more clicks then leaves its own
	// page and moves no later page by one, so none is skipped.
	sorted := slices.Clone(repos)
	sort.Strings(sorted)
	from := min((page-1)*availablePerPage, len(sorted))
	to := min(from+availablePerPage, len(sorted))
	for _, p := range sorted[from:to] {
		if !on[lower(p)] {
			add(p)
		}
	}
	view.HasMore, view.Truncated = to < len(sorted), truncated
	writeJSON(w, http.StatusOK, view)
}

// --- the defaults ---

// defaultsView is the defaults repositories switched on in the dashboard get.
func (d *Dashboard) defaultsView(ctx context.Context) (DefaultsView, error) {
	def, err := d.Repos.BrowserDefaults(ctx, "", "")
	if err != nil {
		return DefaultsView{}, err
	}
	stored, err := d.Store.RepoDefaults(ctx)
	if err != nil {
		return DefaultsView{}, err
	}
	cfg := defaultValues(d.Repos.Defaults("", ""))
	return DefaultsView{Approve: def.Approve, ReviewDrafts: def.ReviewDrafts, InlineFindings: def.InlineFindings, CommandsAuthorAndMaintainersOnly: def.CommandsAuthorAndMaintainersOnly,
		IncrementalReviews: def.IncrementalReviews, LearnFromDismissals: def.LearnFromDismissals, QuietReviews: def.QuietReviews,
		LinkedReposEnabled: def.LinkedReposEnabled,
		CommentLayout:      layoutText(def.CommentLayout),
		FailureStatus:      string(def.FailureStatus),
		JobTimeoutSeconds:  int64(def.JobTimeout / time.Second), MaxTurns: def.MaxTurns, JobMemory: quantityText(def.JobMemory),
		RerunLimitPerMR: def.RerunLimitPerMR, RerunLimitPerRepo: def.RerunLimitPerRepo,
		Skills: nonNil(stored.Skills), Config: cfg, Pinned: pinnedDefaults(stored)}, nil
}

// defaultValues is the settings of eff as the defaults API shows them.
func defaultValues(eff settings.Effective) DefaultValues {
	return DefaultValues{Approve: eff.Approve, ReviewDrafts: eff.ReviewDrafts, InlineFindings: eff.InlineFindings, CommandsAuthorAndMaintainersOnly: eff.CommandsAuthorAndMaintainersOnly,
		IncrementalReviews: eff.IncrementalReviews, LearnFromDismissals: eff.LearnFromDismissals, QuietReviews: eff.QuietReviews,
		LinkedReposEnabled: eff.LinkedReposEnabled,
		CommentLayout:      layoutText(eff.CommentLayout),
		FailureStatus:      string(eff.FailureStatus),
		JobTimeoutSeconds:  int64(eff.JobTimeout / time.Second), MaxTurns: eff.MaxTurns, JobMemory: quantityText(eff.JobMemory),
		RerunLimitPerMR: eff.RerunLimitPerMR, RerunLimitPerRepo: eff.RerunLimitPerRepo}
}

// pinnedDefaults says which defaults were saved in the dashboard, by the
// API's key: those no longer following the config.
func pinnedDefaults(s store.RepoDefaults) map[string]bool {
	return map[string]bool{
		"approve": s.Approve != nil, "reviewDrafts": s.ReviewDrafts != nil, "inlineFindings": s.InlineFindings != nil,
		"commandsAuthorAndMaintainersOnly": s.CommandsAuthorAndMaintainersOnly != nil, "incrementalReviews": s.IncrementalReviews != nil, "learnFromDismissals": s.LearnFromDismissals != nil, "quietReviews": s.QuietReviews != nil,
		"commentLayout": len(s.CommentLayout) > 0, "linkedReposEnabled": s.LinkedReposEnabled != nil,
		"failureStatus": s.FailureStatus != nil, "jobTimeoutSeconds": s.JobTimeoutSeconds != nil, "maxTurns": s.MaxTurns != nil,
		"jobMemory": s.JobMemory != nil, "rerunLimitPerMR": s.RerunLimitPerMR != nil, "rerunLimitPerRepo": s.RerunLimitPerRepo != nil,
	}
}

func (d *Dashboard) getDefaults(w http.ResponseWriter, r *http.Request) {
	v, err := d.defaultsView(r.Context())
	if err != nil {
		d.failed(w, r, "reading the defaults", err)
		return
	}
	writeJSON(w, http.StatusOK, v)
}

func (d *Dashboard) putDefaults(w http.ResponseWriter, r *http.Request) {
	ctx, se := r.Context(), session(r)
	before, err := d.Store.RepoDefaults(ctx)
	if err != nil {
		d.failed(w, r, "reading the defaults", err)
		return
	}
	next, skillsGiven, msg := d.parseDefaults(r, before.Skills)
	if msg != "" {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	if skillsGiven {
		msg, err := d.checkSkillBudget(r, next.Skills)
		if err != nil {
			d.failed(w, r, "checking the skill budget", err)
			return
		}
		if msg != "" {
			writeError(w, http.StatusBadRequest, msg)
			return
		}
	}
	err = d.Store.PutRepoDefaults(ctx, next)
	if msg, ok := skillMissing(err); ok {
		writeError(w, http.StatusBadRequest, msg)
		return
	}
	if err != nil {
		d.Log.Error("dashboard: saving the defaults failed", "error", err.Error())
		writeError(w, http.StatusInternalServerError, msgWriteFailed)
		return
	}
	d.inputs.invalidate()
	changed := changedDefaults(before, next)
	d.Log.Info("dashboard: defaults updated", "fields", changed, "by", se.Username)
	d.audit(ctx, se, "defaults_updated", "", "", strings.Join(changed, ", "))
	if slices.Contains(changed, "skills") {
		d.recheck("", "")
	}
	v, err := d.defaultsView(ctx)
	if err != nil {
		d.failed(w, r, "reading the defaults", err)
		return
	}
	writeJSON(w, http.StatusOK, v)
}

// parseDefaults reads a replacement set of defaults: a JSON object of some
// of the settings, each a valid value (the bounds and messages of a
// repository's settings) or null; the ones left out are the built-in
// default. The exception is skills, the default list of library skills:
// left out it stays as stored (kept), null or [] clears it. skillsGiven says
// the body has the key. It returns the 400's message when the body is wrong.
func (d *Dashboard) parseDefaults(r *http.Request, kept []string) (next store.RepoDefaults, skillsGiven bool, msg string) {
	var fields map[string]json.RawMessage
	if err := decodeStrict(r, &fields); err != nil || fields == nil {
		return store.RepoDefaults{}, false, msgBadDefaults
	}
	row := store.DashboardRepo{Skills: slices.Clone(kept)}
	for key, raw := range fields {
		null := string(bytes.TrimSpace(raw)) == "null"
		var edit func(*store.DashboardRepo)
		var msg string
		switch key {
		case "approve", "reviewDrafts", "inlineFindings", "commandsAuthorAndMaintainersOnly", "incrementalReviews", "learnFromDismissals", "quietReviews", "linkedReposEnabled":
			edit, msg = boolSetting(key, raw, null)
		case "commentLayout":
			edit, msg = commentLayoutSetting(raw, null, msgBadDefaults)
		case "failureStatus":
			edit, msg = failureStatusSetting(raw, null)
		case "skills":
			skillsGiven = true
			edit, msg = defaultSkillsSetting(raw, null)
		case "jobTimeoutSeconds":
			edit, msg = timeoutSetting(raw, null)
		case "maxTurns":
			edit, msg = maxTurnsSetting(raw, null)
		case "jobMemory":
			edit, msg = d.memorySetting(raw, null)
		case "rerunLimitPerMR", "rerunLimitPerRepo":
			edit, msg = rerunLimitSetting(key, raw, null)
		default:
			msg = msgBadDefaults
		}
		if msg != "" {
			return store.RepoDefaults{}, false, msg
		}
		edit(&row)
	}
	return store.RepoDefaults{Approve: row.Approve, ReviewDrafts: row.ReviewDrafts, InlineFindings: row.InlineFindings, CommandsAuthorAndMaintainersOnly: row.CommandsAuthorAndMaintainersOnly, IncrementalReviews: row.IncrementalReviews, LearnFromDismissals: row.LearnFromDismissals, QuietReviews: row.QuietReviews, LinkedReposEnabled: row.LinkedReposEnabled, CommentLayout: row.CommentLayout, FailureStatus: row.FailureStatus,
		JobTimeoutSeconds: row.JobTimeoutSeconds, MaxTurns: row.MaxTurns, JobMemory: row.JobMemory,
		RerunLimitPerMR: row.RerunLimitPerMR, RerunLimitPerRepo: row.RerunLimitPerRepo, Skills: row.Skills}, skillsGiven, ""
}

// defaultSkillsSetting takes null, [] (no default skills) or a list of
// library skill names.
func defaultSkillsSetting(raw json.RawMessage, null bool) (func(*store.DashboardRepo), string) {
	var v []string
	if !null {
		var names []string
		if json.Unmarshal(raw, &names) != nil {
			return nil, "skills must be a list of skills from the library, or null for none"
		}
		var msg string
		if v, msg = skillNames(names); msg != "" {
			return nil, msg
		}
	}
	return func(row *store.DashboardRepo) { row.Skills = v }, ""
}

// changedDefaults names the settings that differ between two sets of
// defaults, in the API's spelling.
func changedDefaults(a, b store.RepoDefaults) []string {
	var out []string
	if !samePtr(a.Approve, b.Approve) {
		out = append(out, "approve")
	}
	if !samePtr(a.ReviewDrafts, b.ReviewDrafts) {
		out = append(out, "reviewDrafts")
	}
	if !samePtr(a.InlineFindings, b.InlineFindings) {
		out = append(out, "inlineFindings")
	}
	if !samePtr(a.CommandsAuthorAndMaintainersOnly, b.CommandsAuthorAndMaintainersOnly) {
		out = append(out, "commandsAuthorAndMaintainersOnly")
	}
	if !samePtr(a.IncrementalReviews, b.IncrementalReviews) {
		out = append(out, "incrementalReviews")
	}
	if !samePtr(a.LearnFromDismissals, b.LearnFromDismissals) {
		out = append(out, "learnFromDismissals")
	}
	if !samePtr(a.QuietReviews, b.QuietReviews) {
		out = append(out, "quietReviews")
	}
	if !slices.Equal(a.CommentLayout, b.CommentLayout) {
		out = append(out, "commentLayout")
	}
	if !samePtr(a.LinkedReposEnabled, b.LinkedReposEnabled) {
		out = append(out, "linkedReposEnabled")
	}
	if !samePtr(a.FailureStatus, b.FailureStatus) {
		out = append(out, "failureStatus")
	}
	if !samePtr(a.JobTimeoutSeconds, b.JobTimeoutSeconds) {
		out = append(out, "jobTimeoutSeconds")
	}
	if !samePtr(a.MaxTurns, b.MaxTurns) {
		out = append(out, "maxTurns")
	}
	if !samePtr(a.JobMemory, b.JobMemory) {
		out = append(out, "jobMemory")
	}
	if !samePtr(a.RerunLimitPerMR, b.RerunLimitPerMR) {
		out = append(out, "rerunLimitPerMR")
	}
	if !samePtr(a.RerunLimitPerRepo, b.RerunLimitPerRepo) {
		out = append(out, "rerunLimitPerRepo")
	}
	if !slices.Equal(a.Skills, b.Skills) {
		out = append(out, "skills")
	}
	return out
}

func samePtr[T comparable](a, b *T) bool {
	if a == nil || b == nil {
		return a == b
	}
	return *a == *b
}
