const (
	// operatorTimeout bounds an instance add or change: the check and the
	// connection each reach the platform, and the answer must be written
	// well before the server's 60 s WriteTimeout.
	operatorTimeout = 40 * time.Second
	// maxSecretBytes bounds one secret (a GitHub App private key is about
	// 1.7 KB).
	maxSecretBytes = 16 << 10

	msgBadInstanceBody   = `the body must be {"name": ..., "platform": "gitlab" or "github", "url" (GitLab) or "apiURL" and "reviewAppID" (GitHub), "secrets": {...}}`
	msgBadInstanceUpdate = `the body must be {"secrets": {...}}`
	msgBadInstanceName   = `the name must be 1 to 63 lowercase letters, digits or "-"`
	msgBadPlatform       = `platform must be "gitlab" or "github"`
	msgInstanceTaken     = "an instance with this name exists already, in the config file or the dashboard"
	msgBadGitLabURL      = "url must be the https address of the GitLab server, without a trailing slash"
	msgBadAPIURL         = "apiURL must be the https address of the GitHub API, without a trailing slash"
	msgGitLabFields      = "a GitLab instance takes a url, not apiURL or App IDs"
	msgGitHubFields      = "a GitHub instance takes apiURL, reviewAppID and approveAppID, not url or approveWithReviewBot"
	msgBadAppIDs         = "reviewAppID must be positive, and approveAppID 0 (a bot user's token approves), the reviewAppID (the review App approves) or another positive App ID"
	msgWebhookGenerated  = "a GitLab instance's webhook_secret is generated by pergent.sh: don't send one"
	msgImmutable         = "an instance's address and App IDs can't change: remove it and add it again"
	msgConfigInstance    = "this instance is managed by the config file; change it there"
	msgInstanceRemoving  = "this instance is being removed"
	msgBadTrustMode      = `the body must be {"mode": "follow_visibility" | "on" | "off"}`
	msgNothingToChange   = `nothing to change: give "secrets"`

	msgBadDefaults    = "the body must be a JSON object of defaults: approve, reviewDrafts, inlineFindings, commandsAuthorAndMaintainersOnly, incrementalReviews, learnFromDismissals, quietReviews, commentLayout, linkedReposEnabled, failureStatus, jobTimeoutSeconds, maxTurns, jobMemory, rerunLimitPerMR, rerunLimitPerRepo"
	instanceNameLimit = 63
)

var instanceNamePattern = regexp.MustCompile(`^[a-z0-9-]+$`)

